/** Strict browser-side decoder for the native canonical V2 public payload. */
export interface CanonicalPublicSummaryV2 {
  network: string;
  electionId: string;
  archiveHashHex: string;
  template: {
    address: string;
    module: string;
    function: string;
    eventTopic: string;
    artifactDigestHex: string;
  };
}

const SCHEMA = "TARI_CC_PRIVATE_BALLOT_OOTLE_ANCHOR_PUBLIC_V2";
const HEX_64 = /^[0-9a-f]{64}$/;
const encoder = new TextEncoder();

function fail(): never {
  throw new Error("the public summary is not the canonical native V2 payload");
}

function object(value: unknown, keys: readonly string[]): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) fail();
  const record = value as Record<string, unknown>;
  const actual = Object.keys(record);
  if (actual.length !== keys.length || actual.some((key, index) => key !== keys[index])) fail();
  return record;
}

function text(value: unknown, max: number, allowEmpty = true): string {
  if (typeof value !== "string" || (!allowEmpty && value.length === 0) || encoder.encode(value).length > max) fail();
  return value;
}

function hex(value: unknown): string {
  if (typeof value !== "string" || !HEX_64.test(value)) fail();
  return value;
}

function machineId(value: unknown): string {
  if (typeof value !== "string" || !/^[0-9a-f]{2,128}$/.test(value) || value.length % 2 !== 0) fail();
  return value;
}

function count(value: unknown): number {
  if (typeof value !== "number" || !Number.isSafeInteger(value) || value < 0) fail();
  return value;
}

/**
 * Parses and then byte-for-byte re-encodes the exact ordered JSON generated by
 * `OotleAnchorPublicPayloadV2::to_canonical_json_bytes`. JSON accepted merely
 * by a generic parser (including reordered, duplicate, or extra fields) is
 * intentionally rejected.
 */
export function parseCanonicalPublicSummaryV2(source: string): CanonicalPublicSummaryV2 {
  if (encoder.encode(source).length === 0 || encoder.encode(source).length > 256 * 1024) fail();
  let value: unknown;
  try {
    value = JSON.parse(source);
  } catch {
    fail();
  }
  const keys = [
    "schema", "version", "network", "election_id", "question", "eligible_voters",
    "accepted_ballots", "rejected_ballots", "results", "ballot_kind", "confidentiality_mode",
    "proof_suite", "manifest_hash", "archive_hash", "voter_registry_commitment",
    "ballot_option_commitment", "archive_finalized", "finalized_timestamp_unix_secs",
    "template_address", "template_module", "template_function", "template_event_topic",
    "template_artifact_digest",
  ] as const;
  const parsed = object(value, keys);
  if (parsed.schema !== SCHEMA || parsed.version !== 2) fail();
  const network = text(parsed.network, 64, false);
  const electionId = text(parsed.election_id, 128, false);
  if ([...electionId].some((character) => character.codePointAt(0)! < 0x20)) fail();
  const question = text(parsed.question, 8 * 1024);
  const eligibleVoters = count(parsed.eligible_voters);
  const acceptedBallots = count(parsed.accepted_ballots);
  const rejectedBallots = count(parsed.rejected_ballots);
  if (!Array.isArray(parsed.results) || parsed.results.length > 65_536) fail();
  const results = parsed.results.map((entry) => {
    const tally = object(entry, ["label", "machine_id", "votes"]);
    return {
      label: text(tally.label, 1024),
      machine_id: machineId(tally.machine_id),
      votes: count(tally.votes),
    };
  });
  const ballotKind = text(parsed.ballot_kind, 64, false);
  const confidentialityMode = text(parsed.confidentiality_mode, 64, false);
  const proofSuite = text(parsed.proof_suite, 64, false);
  const manifestHash = hex(parsed.manifest_hash);
  const archiveHash = hex(parsed.archive_hash);
  const voterRegistryCommitment = hex(parsed.voter_registry_commitment);
  const ballotOptionCommitment = hex(parsed.ballot_option_commitment);
  if (typeof parsed.archive_finalized !== "boolean" || parsed.archive_finalized !== true) fail();
  const finalizedTimestamp = parsed.finalized_timestamp_unix_secs;
  if (finalizedTimestamp !== null) count(finalizedTimestamp);
  const templateAddress = text(parsed.template_address, 512, false);
  const templateModule = text(parsed.template_module, 512, false);
  const templateFunction = text(parsed.template_function, 512, false);
  const templateEventTopic = text(parsed.template_event_topic, 512, false);
  const templateArtifactDigest = hex(parsed.template_artifact_digest);
  const canonical = JSON.stringify({
    schema: SCHEMA,
    version: 2,
    network,
    election_id: electionId,
    question,
    eligible_voters: eligibleVoters,
    accepted_ballots: acceptedBallots,
    rejected_ballots: rejectedBallots,
    results,
    ballot_kind: ballotKind,
    confidentiality_mode: confidentialityMode,
    proof_suite: proofSuite,
    manifest_hash: manifestHash,
    archive_hash: archiveHash,
    voter_registry_commitment: voterRegistryCommitment,
    ballot_option_commitment: ballotOptionCommitment,
    archive_finalized: true,
    finalized_timestamp_unix_secs: finalizedTimestamp,
    template_address: templateAddress,
    template_module: templateModule,
    template_function: templateFunction,
    template_event_topic: templateEventTopic,
    template_artifact_digest: templateArtifactDigest,
  });
  if (canonical !== source) fail();
  return {
    network,
    electionId,
    archiveHashHex: archiveHash,
    template: {
      address: templateAddress,
      module: templateModule,
      function: templateFunction,
      eventTopic: templateEventTopic,
      artifactDigestHex: templateArtifactDigest,
    },
  };
}
